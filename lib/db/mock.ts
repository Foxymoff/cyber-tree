/**
 * Моковые данные для работы без базы.
 *
 * Нужны в двух местах: по ним отлаживают форму и админку, пока нет Neon,
 * и ими наполняют дерево на /display, чтобы было что смотреть на скриншотах.
 *
 * Состав набора детерминированный: одни и те же id, имена, тексты, статусы
 * и порядок при каждом запуске. От этого зависит отладка дерева по скриншотам —
 * лист получает точку крепления по порядку поступления, и если порядок поплывёт,
 * картинка перестанет повторяться.
 *
 * А вот абсолютные метки времени — НЕ фиксированная дата, и это важно.
 * Захардкоженная дата мероприятия оказывается в будущем, пока мероприятие не
 * наступило, и тогда любое действие модератора проставляет updated_at раньше
 * моковых меток. Курсор опроса от этого ломается насмерть: /display никогда не
 * узнает, что лист сняли с экрана. Поэтому набор всегда лежит в недавнем прошлом
 * относительно старта процесса.
 */
import { SPECIALTIES } from '@/config/specialties';
import type { Wish, WishStatus } from '@/lib/types';

/**
 * Точка отсчёта: два часа назад от старта процесса. Весь набор укладывается
 * примерно в час, так что самая свежая метка гарантированно в прошлом, и любое
 * изменение через админку получает метку строго позже неё.
 */
const BASE = Date.now() - 2 * 60 * 60 * 1000;

/** Метка времени через N минут от точки отсчёта, в ISO. */
function at(minutes: number): string {
  return new Date(BASE + minutes * 60_000).toISOString();
}

